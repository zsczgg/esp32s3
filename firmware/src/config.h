// BLE 单次 MTU 请求值（越大越快，247 是兼容性较好的选择）
#define BLE_MTU     247

// ============================================================
// 4. 打印任务边界判定
// ============================================================
// 收到最后一个字节后静默多久，判定"这一票发完了"
// 太小会把一票切成几段，太大则延迟明显。300ms 是经验值
#define JOB_IDLE_MS    300

// 单票最大字节数（超过就截断提交，防止内存打爆）
// 纯文字小票 1~3KB 足够；要打图片位图就得加大
#define JOB_MAX_BYTES  8192

// 兜底：从收到第一个字节起超过这么久还没触发 idle，强制提交
#define JOB_HOLD_MS    8000

// ============================================================
// 5. 调试
// ============================================================
// 1 = 每票都在串口打印 hex（抓协议必备），0 = 关闭
#define DUMP_HEX       1

// 板载 LED；没有 LED 或不想用就设 -1
//   ESP32-C3-DevKitM-1 -> GPIO8（WS2812，用 digitalWrite 只会亮/灭）
//   ESP32-S3-DevKitC-1 -> GPIO48（WS2812）
// 这块 S3 板灯型不确定，先关掉（-1）避免误驱动；确认型号后可改 48
#define LED_PIN        (-1)
#define LED_ACTIVE_LOW 1     // 低电平点亮就设 1，反之为 0

